const schemaDir = "../../../packages/platform-protocol/schema"

func TestGenerateIsDeterministic(t *testing.T) {
	first, err := generate(schemaDir)
	if err != nil {
		t.Fatal(err)
	}
	second, err := generate(schemaDir)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"claims.go", "constants.go", "errors.go", "inputs.go", "routes.go", "tunnel.go"}
	if len(first) != len(want) {
		t.Fatalf("生成了 %d 个文件，应为 %d 个", len(first), len(want))
	}
	for _, name := range want {
		if len(first[name]) == 0 {
			t.Errorf("%s 是空的", name)
		}
		if !bytes.Equal(first[name], second[name]) {
			t.Errorf("%s 两次生成不一致", name)
		}
		if !strings.HasPrefix(string(first[name]), "// Code generated by tools/schemagen; DO NOT EDIT.\n// 生成物，勿手改") {
			t.Errorf("%s 缺文件头", name)
		}
	}
}

func TestPascal(t *testing.T) {
	cases := map[string]string{
		"sourceId":           "SourceID",
		"remoteIp":           "RemoteIP",
		"ed25519-public-jwk": "Ed25519PublicJWK",
		"TOKEN_HASH_KINDS":   "TokenHashKinds",
		"SCRYPT":             "Scrypt",
		"ttlMs":              "TTLMs",
		"e2e":                "E2E",
		"nonce2":             "Nonce2",
		"bad_request":        "BadRequest",
	}
	for in, want := range cases {
		if got := pascal(in); got != want {
			t.Errorf("pascal(%q) = %q，应为 %q", in, got, want)
		}
	}
}

func TestUnknownKeywordStopsTheGenerator(t *testing.T) {
	root, err := parseOrdered([]byte(`{"type":"object","properties":{"a":{"type":"string","format":"date-time"}},"required":["a"]}`))
	if err != nil {
		t.Fatal(err)
	}
	if err := newStructGen().add("X", "x.json", root); err == nil || !strings.Contains(err.Error(), "format") {
		t.Fatalf("应因不认识的关键字失败，实际 %v", err)
	}
}

func TestNestedObjectsWithTheSameShapeShareAType(t *testing.T) {
	root, err := parseOrdered([]byte(`{"type":"object","properties":{
		"a":{"type":"object","properties":{"n":{"type":"integer"}},"required":["n"]},
		"b":{"type":"object","properties":{"n":{"type":"integer"}},"required":["n"]}},
		"required":["a","b"]}`))
	if err != nil {
		t.Fatal(err)
	}
	g := newStructGen()
	if err := g.add("X", "x.json", root); err != nil {
		t.Fatal(err)
	}
	if len(g.defs) != 2 {
		t.Fatalf("应有 2 个类型（XA 与 X），实际 %d", len(g.defs))
	}
}

