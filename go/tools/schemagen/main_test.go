func TestInputsMergeParametersAndBody(t *testing.T) {
	root, err := parseOrdered([]byte(`{"paths":{"/v1/x/{id}":{"post":{"operationId":"x.y",
		"parameters":[{"name":"id","in":"path","required":true,"schema":{"type":"string"}},
		{"name":"n","in":"query","required":false,"schema":{"type":"integer","default":3}}],
		"requestBody":{"required":true,"content":{"application/json":{"schema":{"type":"object",
		"properties":{"a":{"type":"string"}},"required":["a"]}}}}}},
		"/v1/z":{"get":{"operationId":"z.w","parameters":[{"name":"e","in":"query","required":true,"schema":{"type":"string","format":"date-time"}}]}}}}`))
	if err != nil {
		t.Fatal(err)
	}
	out, err := genInputs(root)
	if err != nil {
		t.Fatal(err)
	}
	text := string(out)
	for _, want := range []string{`"x.y": &schema.Schema{`, `{Name: "id"`, `{Name: "n"`, `{Name: "a"`, `Required: []string{"id", "a"}`,
		`var UnsupportedInputs = map[string]string{`, `"z.w": "format"`} {
		if !strings.Contains(text, want) {
			t.Errorf("生成物缺 %q：\n%s", want, text)
		}
	}
	if strings.Contains(text, `"z.w": &schema.Schema`) {
		t.Error("不支持的过程不该进 RouteInputs")
	}
}

// format、minItems、propertyNames 现在都生成成字面量；认不得的 format 与非空 additionalProperties 仍登记为不支持。
func TestGenInputsHandlesFormatsAndRecords(t *testing.T) {
	old := emailPattern
	emailPattern = `^a$`
	t.Cleanup(func() { emailPattern = old })
	root, err := parseOrdered([]byte(`{"paths":{"/v1/x":{"post":{"operationId":"x.y",
		"requestBody":{"required":true,"content":{"application/json":{"schema":{"type":"object",
		"properties":{"e":{"type":"string","format":"email"},"u":{"type":"string","format":"uri","maxLength":9},
		"l":{"type":"array","items":{"type":"string"},"minItems":1},
		"r":{"type":"object","propertyNames":{"type":"string"},"additionalProperties":{}}},"required":["e"]}}}}}},
		"/v1/z":{"post":{"operationId":"z.w","requestBody":{"content":{"application/json":{"schema":{"type":"object",
		"properties":{"m":{"type":"object","additionalProperties":{"type":"string"}}}}}}}}}}}`))
	if err != nil {
		t.Fatal(err)
	}
	out, err := genInputs(root)
	if err != nil {
		t.Fatal(err)
	}
	text := strings.Join(strings.Fields(string(out)), " ")
	for _, want := range []string{`Format: "email"`, `FormatPattern: "^a$"`, `Format: "uri"`, `MinItems: schema.Int(1)`,
		`PropertyNames: &schema.Schema{`, `"z.w": "additionalProperties"`} {
		if !strings.Contains(text, want) {
			t.Errorf("生成物缺 %q：\n%s", want, text)
		}
	}
}

// zod 4.6 的等价写法（可空的 type 数组、startsWith 带的 format、元组的 items: false）
// 归一后与旧写法生成同样的规则；认不出的 type 数组照旧报错。
func TestNormalizeZodEquivalents(t *testing.T) {
	parse := func(src string) *value {
		t.Helper()
		v, err := parseOrdered([]byte(src))
		if err != nil {
			t.Fatal(err)
		}
		if err := normalize(v); err != nil {
			t.Fatal(err)
		}
		return v
	}
	lit := func(v *value) string {
		t.Helper()
		out, err := literal(v)
		if err != nil {
			t.Fatal(err)
		}
		return out
	}
	newer := parse(`{"type":"object","properties":{
		"o":{"type":["string","null"]},
		"p":{"type":"string","format":"starts_with","pattern":"^\\/.*"},
		"h":{"type":"array","items":{"type":"array","prefixItems":[{"type":"string"},{"type":"string"}],"items":false}}},
		"required":["o","p","h"]}`)
	older := parse(`{"type":"object","properties":{
		"o":{"anyOf":[{"type":"string"},{"type":"null"}]},
		"p":{"type":"string","pattern":"^\\/.*"},
		"h":{"type":"array","items":{"type":"array","prefixItems":[{"type":"string"},{"type":"string"}]}}},
		"required":["o","p","h"]}`)
	if got, want := lit(newer), lit(older); got != want {
		t.Fatalf("归一后的规则不同：\n%s\n应为\n%s", got, want)
	}
	if err := newStructGen().add("X", "x.json", newer); err != nil {
		t.Fatal(err)
	}
	bad, err := parseOrdered([]byte(`{"type":["string","integer"]}`))
	if err != nil {
		t.Fatal(err)
	}
	if err := normalize(bad); err == nil {
		t.Fatal("type 数组 [string, integer] 应报错")
	}
}
