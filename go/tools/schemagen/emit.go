package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

const header = `// Code generated by tools/schemagen; DO NOT EDIT.
// 生成物，勿手改：来自 packages/platform-protocol/schema/，改协议包后重新运行 go generate。

`

// file 累积一个生成文件的内容。
type file struct {
	buf bytes.Buffer
}

func (f *file) printf(format string, args ...any) {
	fmt.Fprintf(&f.buf, format, args...)
}

// source 套上文件头与 package 行，再交给 gofmt 排版；排版失败说明生成的代码有错。
func (f *file) source(pkg, doc string, imports []string) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header)
	if doc != "" {
		out.WriteString(doc)
	}
	fmt.Fprintf(&out, "package %s\n\n", pkg)
	if len(imports) > 0 {
		out.WriteString("import (\n")
		for _, path := range imports {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		out.WriteString(")\n\n")
	}
	out.Write(f.buf.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt 失败：%w\n%s", err, out.String())
	}
	return formatted, nil
}

func quote(s string) string { return strconv.Quote(s) }
